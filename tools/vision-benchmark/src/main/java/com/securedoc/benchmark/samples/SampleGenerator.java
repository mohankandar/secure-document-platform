    List<PageSpec> package60() {
        FakeData.Person p = fake.person();
        List<PageSpec> pages = new ArrayList<>();
        pages.add(loanApplication(p, Mode.DIGITAL, "TYPED", "FAST_SIGNATURE", true));
        pages.add(creditReport(p, Mode.DIGITAL, "TYPED", "FAST_SIGNATURE", true));
        for (int i = 0; i < 60; i++) {
            if (pages.size() == 60) break;
            int n = pages.size() + 1;
            if (n == 18) pages.add(handwrittenForm(p, Mode.SCAN_CLEAN, BLUE_INK));
            else if (n == 31) pages.add(idCopy(p, CardKind.DRIVER_LICENCE, Mode.SCAN_CLEAN));
            else if (n == 32) pages.add(checkCopy(p, Mode.SCAN_CLEAN));
            else if (n == 44) pages.add(loanApplication(p, Mode.FAX, "FAX", null, true));
            else if (n == 20 || n == 40 || n == 59) pages.add(signaturePage(p, Mode.DIGITAL, "TYPED", "FAST_SIGNATURE"));
            else if (n == 10) pages.add(bankStatement(p, Mode.SCAN_CLEAN, "TYPED", "FAST"));
            else if (n % 7 == 0) pages.add(disclosure(100 + n, Mode.SCAN_CLEAN, "TYPED", "FAST_SIGNATURE", true));
            else if (n == 60) pages.add(disclosure(100 + n, Mode.DIGITAL, "TYPED", "FAST", false));
            else pages.add(disclosure(100 + n, Mode.DIGITAL, "TYPED", "FAST_SIGNATURE", true));
        }
        return pages;
    }

