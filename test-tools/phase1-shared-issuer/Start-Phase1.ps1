#Requires -Version 5.1
<#
.SYNOPSIS
  PHASE 1 TEST ENVIRONMENT ONLY. Starts the throwaway PostgreSQL and Keycloak, the Phase 1
  backend on port 18080 (schema 001-036 plus staged migration 037 via the test-only changelog),
  proves where it connected, and seeds the two entities.

.DESCRIPTION
  - Never builds. Reuses backend\securedoc-api\target\securedoc-api-0.1.0-SNAPSHOT.jar only when
    -JarBuiltFromCommit names the commit it was built from and git shows no backend change since
    (otherwise stops and asks for a build).
  - Generates every password at start-up into C:\dev\lexavault\phase1-run\secrets (outside the repo).
  - Never prints passwords or tokens.
  - Runs beside the normal LexaVault: it does not use 5432, 8080, 5173, 8181 or the .run folder.
#>
[CmdletBinding()]
param(
    [int]$StartupTimeoutSeconds = 240,
    [string]$JarBuiltFromCommit
)

. (Join-Path $PSScriptRoot 'Phase1-Common.ps1')

function Write-Step([string]$Text) { Write-Host "[phase1] $Text" }

# ---------------------------------------------------------------- 0. Pre-flight
& docker info --format '{{.ServerVersion}}' *> $null
if ($LASTEXITCODE -ne 0) { throw 'Docker is not reachable. Start Docker Desktop, then run this again.' }

$existing = Get-Phase1OwnedProcess 'backend'
if ($existing) { throw "The Phase 1 backend is already running (PID $($existing.ProcessId)). Run Remove-Phase1.ps1 -KeepContainers first." }
if (Test-Phase1Port $Phase1.BackendPort) { throw "Port $($Phase1.BackendPort) is already in use by something that is not the Phase 1 backend." }

$jar = Join-Path $Phase1.RepoRoot 'backend\securedoc-api\target\securedoc-api-0.1.0-SNAPSHOT.jar'
if (-not (Test-Path $jar)) { throw "Backend jar not found: $jar. Build first (cd backend; mvn clean install) with the normal backend stopped." }
# The jar is reused only when the caller names the commit it was built from (-JarBuiltFromCommit),
# backend/ has no uncommitted changes, and git shows no backend change between that commit and HEAD.
# (File timestamps are not used: branch checkouts rewrite them without changing content.)
if (-not $JarBuiltFromCommit) {
    throw 'Name the commit the jar was built from with -JarBuiltFromCommit <sha>, or rebuild (cd backend; mvn clean install) with the normal backend stopped.'
}
$dirty = & git -C $Phase1.RepoRoot status --porcelain -- backend
& git -C $Phase1.RepoRoot diff --quiet $JarBuiltFromCommit HEAD -- backend
$backendChanged = ($LASTEXITCODE -ne 0)
if ($dirty -or $backendChanged) {
    throw "backend/ differs from $JarBuiltFromCommit (or has uncommitted changes). Rebuild with the normal backend stopped."
}
Write-Step "Reusing jar built $((Get-Item $jar).LastWriteTime): no backend change between $JarBuiltFromCommit and HEAD, and backend/ is clean."

Assert-Phase1JdbcUrl $Phase1.JdbcUrl

foreach ($dir in @($Phase1.RunRoot, $Phase1.SecretsDir, $Phase1.PidDir, $Phase1.LogDir, $Phase1.ResultsDir,
                   (Join-Path $Phase1.RunRoot 'storage'), (Join-Path $Phase1.RunRoot 'output'),
                   (Join-Path $Phase1.RunRoot 'watched-intake'))) {
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
}

# ---------------------------------------------------------------- 1. Secrets (outside the repository)
if (-not (Test-Path $Phase1.EnvFile)) {
    Write-Step 'Generating throwaway database and Keycloak admin passwords.'
    @(
        '# PHASE 1 throwaway secrets. Generated by Start-Phase1.ps1. Removed by Remove-Phase1.ps1.',
        "PHASE1_DB_PASSWORD=$(New-Phase1Secret 32)",
        "PHASE1_KC_ADMIN_PASSWORD=$(New-Phase1Secret 32)"
    ) | Set-Content -LiteralPath $Phase1.EnvFile -Encoding ASCII
}
if (-not (Test-Path $Phase1.UsersFile)) {
    Write-Step 'Generating test user passwords.'
    $users = [ordered]@{}
    foreach ($u in ($Phase1.Users + $Phase1.OtherUsers)) { $users[$u] = New-Phase1Secret 24 }
    $users | ConvertTo-Json | Set-Content -LiteralPath $Phase1.UsersFile -Encoding ASCII
}
& icacls $Phase1.SecretsDir /inheritance:r /grant:r "$($env:USERNAME):(OI)(CI)F" *> $null
$secrets = Read-Phase1EnvFile

# ---------------------------------------------------------------- 2. Containers
Write-Step 'Normal containers before start:'
Get-Phase1NormalContainerState | ForEach-Object { Write-Host ("    {0,-20} {1}" -f $_.Name, $_.Status) }

Write-Step 'Starting throwaway PostgreSQL and Keycloak (project lexavault-phase1).'
Invoke-Phase1Compose @('up', '-d', '--wait', 'postgres')
Invoke-Phase1Compose @('up', '-d', 'keycloak')

function Wait-ForUrl([string]$Url, [int]$TimeoutSeconds) {
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    while ((Get-Date) -lt $deadline) {
        try {
            $r = Invoke-WebRequest -Uri $Url -UseBasicParsing -TimeoutSec 5
            if ($r.StatusCode -eq 200) { return $r }
        } catch { }
        Start-Sleep -Seconds 3
    }
    throw "Timed out waiting for $Url"
}

Write-Step 'Waiting for Keycloak realms.'
$disc = Wait-ForUrl "$($Phase1.Issuer)/.well-known/openid-configuration" $StartupTimeoutSeconds
$discIssuer = ($disc.Content | ConvertFrom-Json).issuer
if ($discIssuer -ne $Phase1.Issuer) { throw "Keycloak issuer is '$discIssuer', expected '$($Phase1.Issuer)'." }
[void](Wait-ForUrl "http://localhost:$($Phase1.KeycloakPort)/realms/$($Phase1.OtherRealm)/.well-known/openid-configuration" 60)
Write-Step "Keycloak issuer confirmed: $discIssuer"

# Set the generated user passwords through the admin API (never echoed).
$adminToken = (Invoke-RestMethod -Method Post -Uri "http://localhost:$($Phase1.KeycloakPort)/realms/master/protocol/openid-connect/token" `
    -ContentType 'application/x-www-form-urlencoded' `
    -Body @{ grant_type = 'password'; client_id = 'admin-cli'; username = 'phase1-admin'; password = $secrets['PHASE1_KC_ADMIN_PASSWORD'] }).access_token
$userPasswords = Get-Content -LiteralPath $Phase1.UsersFile -Raw | ConvertFrom-Json
$adminHeaders = @{ Authorization = "Bearer $adminToken" }

# The realm import ignores realms that already exist: bring the running clients in line with the realm files.
Sync-Phase1KeycloakClients
foreach ($pair in @(@($Phase1.Realm, $Phase1.Users), @($Phase1.OtherRealm, $Phase1.OtherUsers))) {
    $realm = $pair[0]
    foreach ($u in $pair[1]) {
        $foundRaw = Invoke-RestMethod -Uri "http://localhost:$($Phase1.KeycloakPort)/admin/realms/$realm/users?exact=true&username=$u" -Headers $adminHeaders
        $found = @($foundRaw)
        if ($found.Count -ne 1) { throw "Keycloak user $u not found in realm $realm (realm import problem)." }
        $body = @{ type = 'password'; value = $userPasswords.$u; temporary = $false } | ConvertTo-Json
        Invoke-RestMethod -Method Put -Uri "http://localhost:$($Phase1.KeycloakPort)/admin/realms/$realm/users/$($found[0].id)/reset-password" `
            -Headers $adminHeaders -ContentType 'application/json' -Body $body | Out-Null
    }
}
$adminToken = $null; $adminHeaders = $null
Write-Step 'Test user passwords set (stored only in the secrets folder).'

# ---------------------------------------------------------------- 3. Backend
$runJar = Join-Path $Phase1.RunRoot 'securedoc-api-phase1.jar'
Copy-Item -LiteralPath $jar -Destination $runJar -Force
$changelog = 'file:' + ((Join-Path $Phase1.ToolDir 'db\phase1-changelog.xml') -replace '\\', '/')
$javaArgs = @(
    '-jar', $runJar,
    '--spring.profiles.active=local,oidc-local',
    "--server.port=$($Phase1.BackendPort)",
    "--spring.datasource.url=$($Phase1.JdbcUrl)",
    "--spring.liquibase.change-log=$changelog",
    "--securedoc.security.oidc.issuer-uri=$($Phase1.Issuer)",
    "--securedoc.security.oidc.audience=$($Phase1.Audience)",
    "--securedoc.security.oidc.provider-id=$($Phase1.ProviderId)",
    "--securedoc.security.oidc.browser-client-id=$($Phase1.WebClientId)",
    '--securedoc.security.oidc.tenant-id=',
    '--securedoc.security.oidc.persistent-connection-enabled=true',
    '--securedoc.security.oidc.shared-issuer-tenant-selection-enabled=true',
    "--securedoc.storage.local.root-path=$(Join-Path $Phase1.RunRoot 'storage')",
    "--securedoc.delivery.local.output-path=$(Join-Path $Phase1.RunRoot 'output')"
)
$childEnv = @{
    SPRING_DATASOURCE_USERNAME                  = $Phase1.DbUser
    SPRING_DATASOURCE_PASSWORD                  = $secrets['PHASE1_DB_PASSWORD']
    SECUREDOC_AI_PROVIDER                       = 'heuristic'
    SECUREDOC_AI_OLLAMA_PRELOAD_ENABLED         = 'false'
    SECUREDOC_WATCHED_FOLDER_ENABLED            = 'false'
    SECUREDOC_WATCHED_FOLDER_SCHEDULING_ENABLED = 'false'
    SECUREDOC_WATCHED_FOLDER_ROOT_PATH          = (Join-Path $Phase1.RunRoot 'watched-intake')
    SECUREDOC_NODE_ID                           = 'PHASE1-APP-01'
    SECUREDOC_LOG_DIR                           = $Phase1.LogDir
    SECUREDOC_SECURITY_CORS_ALLOWED_ORIGINS     = "http://localhost:$($Phase1.UiPort)"
    SECUREDOC_SECURITY_OIDC_TENANT_ID           = ''
}
$saved = @{}
foreach ($k in $childEnv.Keys) { $saved[$k] = [Environment]::GetEnvironmentVariable($k, 'Process'); [Environment]::SetEnvironmentVariable($k, $childEnv[$k], 'Process') }
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$outLog = Join-Path $Phase1.LogDir "backend-$stamp.out.log"
$errLog = Join-Path $Phase1.LogDir "backend-$stamp.err.log"
try {
    Write-Step "Starting Phase 1 backend on port $($Phase1.BackendPort) (shared-issuer setting ON for this process only)."
    $proc = Start-Process -FilePath 'java' -ArgumentList $javaArgs -WorkingDirectory $Phase1.RunRoot `
        -RedirectStandardOutput $outLog -RedirectStandardError $errLog -WindowStyle Hidden -PassThru
} finally {
    foreach ($k in $saved.Keys) { [Environment]::SetEnvironmentVariable($k, $saved[$k], 'Process') }
}
Set-Content -LiteralPath (Get-Phase1PidFile 'backend') -Value $proc.Id -Encoding ASCII
Write-Step "Backend PID $($proc.Id). Logs: $outLog"

$deadline = (Get-Date).AddSeconds($StartupTimeoutSeconds)
$healthy = $false
while ((Get-Date) -lt $deadline) {
    if ($proc.HasExited) { break }
    try {
        $h = Invoke-RestMethod -Uri "$($Phase1.BackendUrl)/actuator/health" -TimeoutSec 5
        if ($h.status -eq 'UP') { $healthy = $true; break }
    } catch { }
    Start-Sleep -Seconds 3
}
if (-not $healthy) {
    Write-Host '--- last backend log lines ---'
    Get-Content -LiteralPath $outLog -Tail 80 -ErrorAction SilentlyContinue
    Get-Content -LiteralPath $errLog -Tail 40 -ErrorAction SilentlyContinue
    throw "Phase 1 backend did not become healthy (exited: $($proc.HasExited))."
}
Write-Step 'Backend is UP.'

# ---------------------------------------------------------------- 4. Proof: where did it connect, and is 037 applied?
$conns = @(Get-NetTCPConnection -OwningProcess $proc.Id -State Established -ErrorAction SilentlyContinue)
$remotePorts = @($conns | ForEach-Object { $_.RemotePort } | Sort-Object -Unique)
Write-Step ("Backend established connections to remote ports: {0}" -f ($remotePorts -join ', '))
if ($remotePorts -contains 5432) { throw 'Phase 1 backend is connected to port 5432 (the normal database). Stopping.' }
if ($remotePorts -notcontains $Phase1.DbPort) { throw 'Phase 1 backend has no connection to port 15432.' }

$schema = Invoke-Phase1Sql @"
select 'changeset_037=' || count(*) from databasechangelog where id = '037-r1b-shared-issuer-active-bindings';
select 'changeset_037_file=' || coalesce(max(filename), '-') from databasechangelog where id = '037-r1b-shared-issuer-active-bindings';
select 'changesets_total=' || count(*) from databasechangelog;
select 'uq_eic_active_binding=' || case when to_regclass('public.uq_eic_active_binding') is null then 'absent' else 'present' end;
select 'uq_eic_active_per_tenant=' || case when to_regclass('public.uq_eic_active_per_tenant') is null then 'absent' else 'present' end;
"@
$schema | ForEach-Object { Write-Host "    $_" }
if (-not ($schema -contains 'changeset_037=1' -and $schema -contains 'uq_eic_active_binding=absent' -and $schema -contains 'uq_eic_active_per_tenant=present')) {
    throw 'Migration 037 is not applied as expected in the throwaway database. Not seeding.'
}

# ---------------------------------------------------------------- 5. Seed
Write-Step 'Seeding the two entities (test-only seed).'
$seedOut = Get-Content -LiteralPath (Join-Path $Phase1.ToolDir 'db\phase1-seed.sql') -Raw |
    & docker exec -i $Phase1.PostgresName psql -U $Phase1.DbUser -d $Phase1.DbName -v ON_ERROR_STOP=1 -At -q -f -
if ($LASTEXITCODE -ne 0) { throw 'Seed failed.' }
$seedOut | ForEach-Object { Write-Host "    $_" }

Write-Step 'Normal containers after start:'
Get-Phase1NormalContainerState | ForEach-Object { Write-Host ("    {0,-20} {1}" -f $_.Name, $_.Status) }
Write-Step 'Phase 1 environment is ready. Next: .\Invoke-Phase1Checks.ps1'
